/** What the build could not settle on its own, written to lists/review.md. */
export interface Review {
  otherPoint: string[];
  fallbacks: string[];
  coordinates: string[];
  prefectureChecks: string[];
  highpoints: string[];
  sharedPlaces: string[];
  numbering: string[];
  routes: string[];
  idReuse: string[];
  islands: string[];
  romaji: string[];
  noEnglish: string[];
}

export const emptyReview = (): Review => ({
  otherPoint: [],
  fallbacks: [],
  coordinates: [],
  prefectureChecks: [],
  highpoints: [],
  sharedPlaces: [],
  numbering: [],
  routes: [],
  idReuse: [],
  islands: [],
  romaji: [],
  noEnglish: [],
});

export const reviewText = (review: Review, header: string[]): string => {
  const section = (title: string, intro: string, lines: string[]) =>
    `## ${title}\n\n${intro}\n\n${lines.length === 0 ? '_None._' : lines.map((line) => `- ${line}`).join('\n')}\n`;
  return [
    '# Reference list review',
    '',
    'Generated by `jam lists build`. Do not edit: fix sources or `lists/overrides.jsonc` and rebuild.',
    '',
    ...header.map((line) => `- ${line}`),
    '',
    section(
      'List points that are not the GSI summit',
      'The list names a different point of the mountain than the summit in GSI’s list (usually the point hikers reach, or a lower top of the same name). The list’s own coordinates are used, as a separate place.',
      review.otherPoint,
    ),
    section(
      'Points with no GSI match',
      'No GSI place nearby with the same name or height. The list’s own coordinates are used.',
      review.fallbacks,
    ),
    section(
      'Coordinates from other sources',
      'Items placed from OpenStreetMap or Wikipedia, or left without coordinates.',
      review.coordinates,
    ),
    section(
      'Prefecture checks',
      'Points that sit well outside a prefecture they are listed in.',
      review.prefectureChecks,
    ),
    section('Prefectural high points that are not summits', 'From GSI’s table.', review.highpoints),
    section('Shared places', 'Several items of one list on the same place.', review.sharedPlaces),
    section('Numbering', 'Items missing a number from their source.', review.numbering),
    section(
      'Routes',
      'Route lists, where their geometry comes from, and any that are not built.',
      review.routes,
    ),
    section('Place ids kept', 'Ids reused from the previous build.', review.idReuse),
    section(
      'Islands',
      'Small islands the simplified outlines dropped, added back from the detailed ones.',
      review.islands,
    ),
    section(
      'English names from kana',
      'Places with no published English name, romanised from their reading.',
      review.romaji,
    ),
    section(
      'Names with no English',
      'No English label on Wikidata and no reading to romanise, so the Japanese name is shown in English too. Add an English name in `lists/overrides.jsonc` (itemCoordinates) where it matters.',
      review.noEnglish,
    ),
  ].join('\n');
};
